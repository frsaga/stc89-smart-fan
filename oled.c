// 显示字符
void OLED_ShowChar(unsigned char x, unsigned char y, unsigned char chr)
{
    unsigned char c = 0, i;
    if(chr >= ' ' && chr <= 'Z')
        c = chr - ' ';
    else
        return;
    
    OLED_SetPos(x, y);
    for(i = 0; i < 6; i++)
    {
        OLED_WriteData(F6x8[c][i]);
    }
}

// 显示字符串
void OLED_ShowString(unsigned char x, unsigned char y, unsigned char *str)
{
    unsigned char j = 0;
    while(str[j] != '\0')
    {
        OLED_ShowChar(x, y, str[j]);
        x += 6;
        if(x > 122)
        {
            x = 0;
            y++;
        }
        j++;
    }
}

// 显示数字
void OLED_ShowNum(unsigned char x, unsigned char y, unsigned int num, unsigned char len)
{
    unsigned char t, temp;
    unsigned char enshow = 0;
    for(t = 0; t < len; t++)
    {
        temp = (num / OLED_Pow(10, len - t - 1)) % 10;
        if(enshow == 0 && t < (len - 1))
        {
            if(temp == 0)
            {
                OLED_ShowChar(x + 6 * t, y, ' ');
                continue;
            }
            else
                enshow = 1;
        }
        OLED_ShowChar(x + 6 * t, y, temp + '0');
    }
}

// 显示有符号数字
void OLED_ShowSignedNum(unsigned char x, unsigned char y, int num, unsigned char len)
{
    unsigned char t, temp;
    unsigned char enshow = 0;
    if(num >= 0)
    {
        OLED_ShowChar(x, y, '+');
    }
    else
    {
        OLED_ShowChar(x, y, '-');
        num = -num;
    }
    for(t = 0; t < len; t++)
    {
        temp = (num / OLED_Pow(10, len - t - 1)) % 10;
        if(enshow == 0 && t < (len - 1))
        {
            if(temp == 0)
            {
                OLED_ShowChar(x + 6 * (t + 1), y, ' ');
                continue;
            }
            else
                enshow = 1;
        }
        OLED_ShowChar(x + 6 * (t + 1), y, temp + '0');
    }
}

// 显示十六进制数字
void OLED_ShowHexNum(unsigned char x, unsigned char y, unsigned int num, unsigned char len)
{
    unsigned char t, temp;
    for(t = 0; t < len; t++)
    {
        temp = (num / OLED_Pow(16, len - t - 1)) % 16;
        if(temp < 10)
            OLED_ShowChar(x + 6 * t, y, temp + '0');
        else
            OLED_ShowChar(x + 6 * t, y, temp - 10 + 'A');
    }
}

// 显示二进制数字
void OLED_ShowBinNum(unsigned char x, unsigned char y, unsigned int num, unsigned char len)
{
    unsigned char t;
    for(t = 0; t < len; t++)
    {
        OLED_ShowChar(x + 6 * t, y, (num / OLED_Pow(2, len - t - 1)) % 2 + '0');
    }
}

