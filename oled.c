#include "oled.h"

// OLED写命令
void OLED_WriteCmd(unsigned char cmd)
{
    I2C_Start();
    I2C_SendByte(OLED_ADDRESS);
    I2C_WaitAck();
    I2C_SendByte(OLED_CMD);
    I2C_WaitAck();
    I2C_SendByte(cmd);
    I2C_WaitAck();
    I2C_Stop();
}

// OLED写数据
void OLED_WriteData(unsigned char dat)
{
    I2C_Start();
    I2C_SendByte(OLED_ADDRESS);
    I2C_WaitAck();
    I2C_SendByte(OLED_DATA);
    I2C_WaitAck();
    I2C_SendByte(dat);
    I2C_WaitAck();
    I2C_Stop();
}

// 设置光标位置
void OLED_SetPos(unsigned char x, unsigned char y)
{
    OLED_WriteCmd(0xB0 + y);
    OLED_WriteCmd(((x & 0xF0) >> 4) | 0x10);
    OLED_WriteCmd((x & 0x0F) | 0x01);
}

// OLED初始化
void OLED_Init(void)
{
    I2C_Init();
    
    // 初始化序列
    OLED_WriteCmd(0xAE); // 关闭显示
    OLED_WriteCmd(0xD5); // 设置时钟分频
    OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); // 设置多路复用率
    OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); // 设置显示偏移
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40); // 设置起始行
    OLED_WriteCmd(0x8D); // 电荷泵设置
    OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); // 内存地址模式
    OLED_WriteCmd(0x00);
    OLED_WriteCmd(0xA1); // 段重映射
    OLED_WriteCmd(0xC8); // COM扫描方向
    OLED_WriteCmd(0xDA); // COM引脚配置
    OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); // 对比度设置
    OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); // 预充电周期
    OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); // VCOMH设置
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4); // 全局显示开启
    OLED_WriteCmd(0xA6); // 正常显示模式
    OLED_WriteCmd(0xAF); // 开启显示
}

// 清屏
void OLED_Clear(void)
{
    unsigned char i, j;
    for(j = 0; j < 8; j++)
    {
        OLED_SetPos(0, j);
        for(i = 0; i < 128; i++)
        {
            OLED_WriteData(0x00);
        }
    }
}

// 辅助函数：计算幂
static unsigned int OLED_Pow(unsigned char m, unsigned char n)
{
    unsigned int result = 1;
    while(n--)
    {
        result *= m;
    }
    return result;
}

